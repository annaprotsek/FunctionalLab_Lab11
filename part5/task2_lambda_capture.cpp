// Частина 5, завдання 2: захоплення змінних у лямбда-виразах.
//
// РЕЗУЛЬТАТ початкового коду: "6 30".
// * [k] - захоплення ЗА ЗНАЧЕННЯМ: у момент створення лямбди значення k (2) копіюється
//   в поле замикання. Подальша зміна зовнішньої k на замикання не впливає:
//   byValue(3) = 3 * 2 = 6.
// * [&k] - захоплення ЗА ПОСИЛАННЯМ: замикання зберігає посилання на ту саму змінну.
//   Після k = 10 лямбда бачить нове значення: byRef(3) = 3 * 10 = 30.
// Тобто різниця не в виразах, а в тому, ЩО зберігає замикання: копію чи посилання.
// Захоплення за посиланням небезпечне, якщо лямбда переживе змінну (висяче посилання).
//
// Додатково показано: лямбда за значенням за замовчуванням має const operator(),
// тому змінювати свою копію можна лише з mutable; а також init-capture [c = k].
#include <iostream>

int main() {
    int k = 2;

    auto byValue = [k](int x) {
        return x * k;
    };

    auto byRef = [&k](int x) {
        return x * k;
    };

    k = 10;

    std::cout << byValue(3) << ' ' << byRef(3) << std::endl;   // 6 30

    // --- додаткові спостереження ---
    int counter = 0;
    auto mutableCopy = [counter](int x) mutable {   // змінюється ВЛАСНА копія counter
        ++counter;
        return x + counter;
    };
    std::cout << mutableCopy(10) << ' ' << mutableCopy(10) << ' '
              << "зовнішній counter = " << counter << '\n';   // 11 12, counter = 0

    auto snapshot = [c = k * 2](int x) { return x + c; };      // init-capture: c = 20
    k = 0;
    std::cout << snapshot(1) << '\n';                           // 21
}
